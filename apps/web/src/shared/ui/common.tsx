// A text input with its label (and optional hint) — the label names the input for screen readers.
export const Input = ({ label, help, ...attrs }: InputHTMLAttributes<HTMLInputElement> & { label: string; help?: string }) => (
  <label className="field">
    <span>{label}</span>
    <input {...attrs} />
    {help ? <small>{help}</small> : null}
  </label>
)
