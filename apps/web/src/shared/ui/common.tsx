// Small layout pieces used on most screens.
import type { InputHTMLAttributes, ReactNode } from "react"
import { ErrorBox } from "./ErrorBox"

export function PageHead({ title, sub, actions }: { title: ReactNode; sub?: ReactNode; actions?: ReactNode }) {
  return (
    <div className="page-head">
      <div>
        <h1>{title}</h1>
        {sub ? <div className="sub">{sub}</div> : null}
      </div>
      <div className="spacer" />
      <div className="row head-actions">{actions}</div>
    </div>
  )
}

export const Loading = () => <p className="loading">Loading…</p>

export function PageError({ error, back }: { error: unknown; back: { href: string; label: string; onClick?: () => void } }) {
  return (
    <div className="card">
      <ErrorBox error={error} />
      <p style={{ marginTop: 12 }}>
        <a className="btn" href={back.href} onClick={back.onClick}>
          {back.label}
        </a>
      </p>
    </div>
  )
}

